// Study protocol (D-046): a study participant sees their six sitting-2 tasks with role-play
// conditions, marks the onset, and opens the frozen material in its own tab. SYNTHETIC (dev tester).
import { expect, test } from "@playwright/test";

test("a study participant gets a plan, role-play cards, onset marking and the study material", async ({ page, browserName }) => {
  // D-025 allows Chrome, Edge and Firefox. Playwright's Chromium reports plain "Chromium" (refused, as it
  // should be) and WebKit is Safari (out of scope), so this runs in Firefox.
  test.skip(browserName !== "firefox", "the study protocol allows Chrome, Edge and Firefox only (D-025)");
  test.setTimeout(120_000);
  await page.goto("/?study=1#/");
  await page.check("#age");
  await page.check("#agree");
  await page.click("#consent-continue");
  await page.waitForURL(/#\/setup/);
  await expect(page.locator("#exam-tasks .slot")).toHaveCount(6);
  const conditions = await page.locator("#exam-tasks .slot").evaluateAll((els) => els.map((e) => e.getAttribute("data-condition")));
  expect(conditions.filter((c) => c === "genuine")).toHaveLength(2);
  expect(new Set(conditions)).toEqual(new Set(["genuine", "A1", "A4", "A5", "A7"]));

  // Sitting 1 first: the exam needs a practice session in the same browser.
  await page.click('button[data-problem="practice_sum_evens"]');
  await page.waitForURL(/#\/session\//);
  await expect(page.locator("#status")).toHaveText("open", { timeout: 30_000 });
  await page.goto("/#/setup");

  await page.locator('#exam-tasks .slot[data-condition="A1"] button').click();
  await page.waitForURL(/#\/session\//);
  await expect(page.locator("#roleplay")).toHaveAttribute("data-condition", "A1");
  await expect(page.locator("#roleplay")).toContainText("no consequences");
  await page.click("#onset");
  await expect(page.locator("#onset-result")).toHaveText("Start marked.");
  await expect(page.locator("#onset")).toBeDisabled();
  const [material] = await Promise.all([page.waitForEvent("popup"), page.click("#open-material")]);
  await expect(material.locator("#material-code")).toContainText("def ");
  await expect(material.locator("main")).toContainText("generated by an AI model");

  await page.goto("/#/setup");
  await expect(page.locator('#exam-tasks .slot[data-condition="A1"] button')).toBeDisabled();   // one session per task
  await page.locator('#exam-tasks .slot[data-condition="genuine"] button').first().click();
  await page.waitForURL(/#\/session\//);
  await expect(page.locator("#roleplay")).toHaveAttribute("data-condition", "genuine");
  await expect(page.locator("#onset")).toHaveCount(0);
});
