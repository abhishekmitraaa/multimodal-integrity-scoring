// Study protocol (D-046, SPEC 12.2): role-play cards, the frozen study material, browser details.
// Conditions are role-play with no consequences (SPEC 12.2). Reviewers never see them.

import { api, type SessionEnv, type StudyCondition } from "../api";
import { detectBrowserVersion } from "../capture/device";
import { h } from "../dom";
import { store } from "../state";

export const ROLEPLAY: Record<StudyCondition, { title: string; text: string; material: boolean; onset: boolean }> = {
  genuine: { title: "Solve it yourself", text: "Solve this task yourself, as you would in a real exam.", material: false, onset: false },
  A1: {
    title: "Role-play: paste a solution",
    text: "Open the study material, copy the solution there and paste it into the editor. Click \"I'm starting now\" just before you open it.",
    material: true, onset: true,
  },
  A4: {
    title: "Role-play: copy-type from another screen",
    text: "Open the study material and type the solution by hand while reading it, as if it were on a second screen. Click \"I'm starting now\" just before you open it.",
    material: true, onset: true,
  },
  A5: {
    title: "Role-play: make generated code look like yours",
    text: "Start from the solution in the study material (paste or type it), then change it so it looks like your own: rename things, reorder, rewrite parts. Click \"I'm starting now\" just before you open it.",
    material: true, onset: true,
  },
  A7: {
    title: "Solve it, then reorganise",
    text: "Solve the task yourself. Before submitting, reorganise your code inside the editor: move a block with cut and paste, or move part of it into a helper function.",
    material: false, onset: false,
  },
  A8: { title: "Solve it on the other keyboard", text: "Use the other keyboard the researcher gives you, and solve the task yourself.", material: false, onset: false },
  A2: { title: "Scripted", text: "", material: false, onset: false },
  A3a: { title: "Scripted", text: "", material: false, onset: false },
  A3b: { title: "Scripted", text: "", material: false, onset: false },
};

let envPromise: Promise<SessionEnv> | undefined;

/** Browser brand and version and cross-origin isolation, sent with every new session (covariates, sitting rules). */
export function sessionEnv(): Promise<SessionEnv> {
  envPromise ??= detectBrowserVersion().then((b) => ({
    browser_brand: b.brand, browser_version: b.version.slice(0, 64), cross_origin_isolated: self.crossOriginIsolated === true,
  }));
  return envPromise;
}

/** The role-play card on an exam page; null when this session has no study condition. */
export async function roleplayCard(sessionId: string, token: string): Promise<HTMLElement | null> {
  const plan = await api.plan(token).catch(() => null);
  const slot = plan?.slots.find((s) => s.session_id === sessionId);
  if (!slot) return null;
  const r = ROLEPLAY[slot.condition];
  const result = h("p", { class: "muted", id: "onset-result" });
  const start = r.onset
    ? h("button", { id: "onset", class: "primary" }, "I'm starting now")
    : null;
  start?.addEventListener("click", async () => {
    try {
      await api.onset(sessionId, Math.round(performance.now() * 1000), token);   // the event log's clock
      start.setAttribute("disabled", "");
      result.textContent = "Start marked.";
    } catch (err) {
      result.textContent = String(err);
    }
  });
  const open = r.material
    ? h("button", { id: "open-material", onclick: () => window.open(`#/material/${sessionId}`, "_blank") }, "Open the study material (new tab)")
    : null;
  return h("section", { class: `roleplay roleplay-${slot.condition}`, id: "roleplay", "data-condition": slot.condition },
    h("strong", {}, r.title),
    h("p", {}, r.text),
    r.onset || r.material ? h("p", { class: "muted" }, "This is role-play for the study, with no consequences.") : null,
    start || open ? h("div", { class: "row" }, start, open) : null,
    result,
  );
}

/** The frozen study material, in its own tab: copying here is not an editor copy, so a paste of it counts as external. */
export async function materialPage(root: HTMLElement, sessionId: string): Promise<void> {
  const participant = store.participant();
  const main = h("main", { class: "narrow" });
  root.replaceChildren(main);
  if (!participant) {
    main.replaceChildren(h("p", {}, "Open the material from your exam page."));
    return;
  }
  try {
    const m = await api.material(sessionId, participant.token);
    main.replaceChildren(
      h("h1", {}, "Study material"),
      h("p", { class: "muted" }, `A solution generated by an AI model (${m.model}, ${m.generated_at}), for the role-play only.`),
      h("pre", { class: "reference-code", id: "material-code" }, m.text),
    );
  } catch (err) {
    main.replaceChildren(h("p", { class: "error" }, String(err)));
  }
}
